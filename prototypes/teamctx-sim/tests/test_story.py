class SafetyTests(unittest.TestCase):
    def setUp(self):
        envfile.REDACTOR.clear()

    def test_a_registered_secret_planted_anywhere_never_reaches_the_story(self):
        envfile.REDACTOR.add(envfile.Secret("PlantedSecretValue-123456", "planted"))
        mapping = json.loads(json.dumps(MAPPING))
        state = json.loads(json.dumps(STATE))
        mapping["items"][K[0]]["content_posted"] = "hello PlantedSecretValue-123456"
        state["captures"]["c01"]["text"] = "Recorded: **D-1** · PlantedSecretValue-123456 — Wren Calloway, <t:1794360005:d>"
        state["asks"]["inj-1"]["text"] = "key PlantedSecretValue-123456 and " + FAKE_KEY
        state["model"] = {"table": {"key": "PlantedSecretValue-123456"}}
        dump = json.dumps(T.build_story(timeline(), mapping, state, DATASET))
        self.assertNotIn("PlantedSecretValue-123456", dump)
        self.assertNotIn(FAKE_KEY, dump)
        self.assertIn("***", dump)

    def test_shape_based_secrets_are_masked_without_registration(self):
        mapping = json.loads(json.dumps(MAPPING))
        mapping["items"][K[0]]["content_posted"] = "token " + FAKE_KEY + " and tctx_FAKEFAKEFAKEFAKE0123456789"
        dump = json.dumps(T.build_story(timeline(), mapping, STATE, DATASET))
        self.assertNotIn("sk-or-v1", dump)
        self.assertNotIn("tctx_FAKE", dump)

    def test_no_snowflake_like_number_appears_in_the_story(self):
        dump = json.dumps(build())
        self.assertEqual(re.findall(r"\d{17,20}", dump), [])
        mapping = json.loads(json.dumps(MAPPING))
        mapping["items"][K[0]]["content_posted"] = "id 123456789012345678 here"
        self.assertEqual(re.findall(r"\d{17,20}", json.dumps(T.build_story(timeline(), mapping, STATE, DATASET))), [])

    def test_no_emulator_urls_or_ids_in_the_story(self):
        dump = json.dumps(build())
        self.assertNotIn("discord.com/channels", dump)
        self.assertNotIn("5000000000000000001", dump)
        self.assertNotIn(str(BASE), dump)

