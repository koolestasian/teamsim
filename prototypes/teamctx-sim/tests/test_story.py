class CleaningTests(unittest.TestCase):
    def test_discord_markup_becomes_plain_words(self):
        raw = "**Recorded** \\- a __plan__ on <t:1775174400:d> (<t:1775174400:D>) [jump](https://discord.com/channels/1/2/3) see https://x.example/y now"
        self.assertEqual(T.clean_markup(raw), "Recorded - a plan on Apr 3 (Apr 3) see now")

    def test_whitespace_collapses_and_lines_can_be_kept(self):
        self.assertEqual(T.clean_markup("a   b\n\n c\t d"), "a b c d")
        self.assertEqual(T.clean_markup("a   b\n\n c  d", keep_lines=True), "a b\nc d")

    def test_jump_links_and_trailing_separators_go(self):
        self.assertEqual(T.clean_markup("**D-1** · title · [jump](https://discord.com/channels/1/2/3)"), "D-1 · title")

    def test_run_date_stamp_is_stripped_after_an_author_only(self):
        self.assertEqual(T.strip_stamp("T — Wren Calloway, Nov 11"), "T — Wren Calloway")
        self.assertEqual(T.strip_stamp("T — owner Pell, due Dec 2"), "T — owner Pell, due Dec 2")

    def test_shorten(self):
        self.assertEqual(T.shorten("short", 10), "short")
        out = T.shorten("one two three four five six", 15)
        self.assertTrue(out.endswith("…") and len(out) <= 15)

    def test_answer_body_drops_disclaimer_sources_and_marks(self):
        raw = STATE["queries"]["act4-ask1"]["text"]
        self.assertEqual(T.answer_body(raw), "The budget is 7,400. Kick-off came first.")


