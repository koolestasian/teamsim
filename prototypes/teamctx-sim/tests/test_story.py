class StoryTests(unittest.TestCase):
    def setUp(self):
        envfile.REDACTOR.clear()
        self.ev = build()

    def test_acts_come_in_order_before_their_first_message(self):
        acts = of(self.ev, "act")
        self.assertEqual([a["n"] for a in acts], [1, 2, 3, 4])
        self.assertEqual(acts[0]["title"], "Kick-off")
        self.assertEqual(acts[2]["title"], "teamctx goes offline")
        self.assertEqual(acts[1]["project_dates"], "Mar 16 – Mar 31")
        order = [e["type"] for e in self.ev]
        self.assertLess(order.index("act"), order.index("message"))
        first_msg_of_act3 = next(i for i, e in enumerate(self.ev) if e["type"] == "message" and e["text"] == "offline chatter")
        act3 = next(i for i, e in enumerate(self.ev) if e["type"] == "act" and e["n"] == 3)
        offline = next(i for i, e in enumerate(self.ev) if e["type"] == "host" and e["state"] == "offline")
        self.assertLess(act3, offline)
        self.assertLess(offline, first_msg_of_act3)

    def test_messages_have_person_channel_text_and_short_ids(self):
        msgs = of(self.ev, "message")
        self.assertEqual([m["id"] for m in msgs][:3], ["s1", "s2", "s3"])
        m = msgs[0]
        self.assertEqual((m["person"], m["person_id"], m["channel"], m["text"]), ("Wren Calloway", "101", "general", "kick-off"))
        self.assertFalse(m["is_bot"] or m["private"])
        self.assertEqual(m["project_date"], "Mar 2")
        leads = next(x for x in msgs if x["channel"] == "leads")
        self.assertTrue(leads["private"])
        self.assertTrue(next(x for x in msgs if x["text"] == "digest")["is_bot"])

    def test_reply_to_maps_to_story_ids(self):
        msgs = of(self.ev, "message")
        self.assertEqual(msgs[1]["reply_to"], "s1")
        self.assertIsNone(msgs[0]["reply_to"])

    def test_edit_uses_the_dataset_text_and_delete_uses_the_story_id(self):
        edit = of(self.ev, "edit")[0]
        self.assertEqual((edit["id"], edit["text"]), ("s2", "second thought"))
        self.assertEqual(of(self.ev, "delete")[0]["id"], "s4")

    def test_extras_inherit_the_last_project_date(self):
        wrong = next(m for m in of(self.ev, "message") if m["text"] == "wrong channel, ignore")
        self.assertEqual(wrong["project_date"], "Mar 3")

    def test_stored_per_message_while_host_is_up(self):
        stored = of(self.ev, "stored")
        self.assertEqual(stored[0]["ids"], ["s1"])
        self.assertEqual(stored[1]["ids"], ["s2"])
        self.assertEqual(stored[0]["note"], "")

